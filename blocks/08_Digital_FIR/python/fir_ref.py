#!/usr/bin/env python3
"""fir_ref.py - CIC droop-compensation FIR (Block 8): design, fixed-point model, test vectors.

Position in the chain: bitstream (4 MHz) -> cic3 (Block 7, R=80) -> fir_comp (this block, 50 kHz).

Design : linear-phase type-I FIR, NTAP taps, least squares (scipy.signal.firls) towards
         1/|H_cic(f)| on 0..FP and towards a gain falling back to 1 on FP+1 kHz..fs_out/2
         (low weight), so the shaped quantisation noise near the band edge is not boosted.
Fixed  : coefficients signed CW bits with F fractional bits; the centre tap is adjusted so
         that sum(q) == 2^F exactly (DC gain exactly 1).
         y[n] = (sum_k q[k] * x[n-k] + 2^(F-1)) >> F   (arithmetic shift = floor),
         the same arithmetic as rtl/fir_comp.v. No overflow is possible: the worst-case
         accumulator and output magnitudes are checked below.
Output : rtl/fir_coefs.vh (case items for the RTL), data/fir_in.mem, data/fir_golden.mem,
         data/fir_golden.txt, data/fir_segments.txt.
Status : SIMULATED_NOT_FINAL_PASS (one 4096-bit closed-loop run feeds the f6 segment).

Checks done on every run:
  1. fixed-point response: |H_cic * H_fir| within the passband limits on 0..FP
  2. bit-exact model == integer convolution (np.convolve, then the same rounding)
  3. worst-case input (+-512000 with the signs of the taps) fits ACC and W_OUT bits
  4. impulse response read back == quantised coefficients; DC step gain == 1 exactly
"""
import argparse
import sys
from pathlib import Path

import numpy as np
from scipy import signal

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "blocks/07_Digital_CIC/python"))
from cic_ref import cic_bitexact, DEF_BS            # noqa: E402

FS = 4e6          # modulator bit rate
R = 80            # CIC decimation
NCIC = 3          # CIC order
FS_OUT = FS / R   # 50 kHz
FULL = R ** NCIC  # CIC full scale 512000


def h_cic(f):
    x = np.pi * np.asarray(f, dtype=float) / FS
    out = np.ones_like(x)
    nz = x != 0
    out[nz] = (np.sin(x[nz] * R) / (R * np.sin(x[nz]))) ** NCIC
    return out


def design(ntap, fp):
    fb = np.linspace(0.0, fp, 200)
    bands, des = [], []
    for a, b in zip(fb[:-1], fb[1:]):
        bands += [a, b]
        des += [1.0 / h_cic([a])[0], 1.0 / h_cic([b])[0]]
    bands += [fp + 1e3, FS_OUT / 2]
    des += [1.0 / h_cic([fp])[0], 1.0]
    weight = [1.0] * (len(fb) - 1) + [0.05]
    return signal.firls(ntap, bands, des, weight=weight, fs=FS_OUT)


def quantise(h, f_bits, cw):
    q = np.round(h * 2 ** f_bits).astype(np.int64)
    q[len(q) // 2] += 2 ** f_bits - int(q.sum())       # DC gain exactly 1
    if np.abs(q).max() >= 2 ** (cw - 1):
        sys.exit("coefficient does not fit in CW bits")
    return q


def fir_bitexact(x, q, f_bits):
    """Same order of operations as the RTL: history shift, MAC over k, round, shift."""
    hist = [0] * len(q)
    out = []
    rnd = 1 << (f_bits - 1)
    for v in x:
        hist = [int(v)] + hist[:-1]
        acc = 0
        for k in range(len(q)):
            acc += int(q[k]) * hist[k]
        out.append((acc + rnd) >> f_bits)
    return out


def fir_conv(x, q, f_bits):
    acc = np.convolve(np.asarray(x, dtype=np.int64), q)[:len(x)]
    return (acc + (1 << (f_bits - 1))) >> f_bits


def write_vh(path, q, cw):
    lines = ["// fir_coefs.vh - generated by python/fir_ref.py, do not edit by hand.",
             f"// {len(q)} taps, signed {cw}-bit, used inside the case statement of fir_comp.coef()."]
    for k, v in enumerate(q):
        lines.append(f"            {k}: coef = {'-' if v < 0 else ''}{cw}'sd{abs(int(v))};")
    path.write_text("\n".join(lines) + "\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--ntap", type=int, default=21)
    ap.add_argument("--fp", type=float, default=15e3, help="compensated passband edge (Hz)")
    ap.add_argument("--f", type=int, default=16, help="fractional bits of the coefficients")
    ap.add_argument("--cw", type=int, default=18, help="coefficient width (Gowin DSP 18x18)")
    ap.add_argument("--acc", type=int, default=38, help="accumulator width in the RTL")
    ap.add_argument("--wout", type=int, default=21, help="output width in the RTL")
    ap.add_argument("--dev", type=float, default=0.12, help="allowed passband deviation (dB)")
    ap.add_argument("--bitstream", default=str(DEF_BS))
    a = ap.parse_args()

    blk = ROOT / "blocks/08_Digital_FIR"
    data = blk / "data"
    data.mkdir(parents=True, exist_ok=True)

    h = design(a.ntap, a.fp)
    q = quantise(h, a.f, a.cw)
    write_vh(blk / "rtl/fir_coefs.vh", q, a.cw)
    print(f"FIR {a.ntap} taps, passband 0..{a.fp / 1e3:.1f} kHz at fs_out {FS_OUT / 1e3:.0f} kHz, "
          f"coefficients {a.cw}-bit with {a.f} fractional bits")
    print("q =", " ".join(str(int(v)) for v in q))

    # 1. response of CIC * fixed-point FIR
    f = np.linspace(0, FS_OUT / 2, 4001)
    _, hf = signal.freqz(q / 2 ** a.f, worN=f, fs=FS_OUT)
    tot = np.abs(hf) * h_cic(f)
    m = f <= a.fp
    dmin, dmax = 20 * np.log10(tot[m].min()), 20 * np.log10(tot[m].max())
    g_edge = 20 * np.log10(np.abs(hf[-1]))
    g_max = 20 * np.log10(np.abs(hf).max())
    f_tone = 13.0 / 4096.0 * FS
    g_tone = float(np.abs(signal.freqz(q / 2 ** a.f, worN=[f_tone], fs=FS_OUT)[1][0]) * h_cic([f_tone])[0])
    ok1 = max(abs(dmin), abs(dmax)) <= a.dev
    print(f"check 1 CIC*FIR on 0..{a.fp / 1e3:.0f} kHz: {dmin:+.3f}/{dmax:+.3f} dB (limit +-{a.dev}) : "
          f"{'PASS' if ok1 else 'FAIL'}")
    print(f"        FIR max gain {g_max:.2f} dB, FIR gain at {FS_OUT / 2e3:.0f} kHz {g_edge:+.2f} dB, "
          f"CIC*FIR at the {f_tone / 1e3:.2f} kHz test tone {g_tone:.5f} (CIC alone {h_cic([f_tone])[0]:.5f})")

    # test vectors (one continuous stream; segments listed in data/fir_segments.txt)
    rng = np.random.default_rng(2026)
    sgn = np.where(q >= 0, 1, -1)
    seg = []
    seg.append(("impulse", [100000] + [0] * (a.ntap + 4)))
    seg.append(("step_pos", [FULL] * (a.ntap + 5)))
    seg.append(("step_neg", [-FULL] * (a.ntap + 5)))
    seg.append(("worst_pos", list((FULL * sgn[::-1]).astype(int)) + [0] * 2))
    seg.append(("worst_neg", list((-FULL * sgn[::-1]).astype(int)) + [0] * 2))
    seg.append(("random", list(rng.integers(-FULL, FULL + 1, 200))))
    bits = (np.loadtxt(a.bitstream)[:4096] > 0).astype(int)
    cic_out = cic_bitexact(bits[:4080], NCIC, R, 20)
    seg.append(("f6_cic", cic_out))
    x = [int(v) for _, s in seg for v in s]

    y = fir_bitexact(x, q, a.f)
    yc = fir_conv(x, q, a.f)
    ok2 = np.array_equal(np.array(y), yc)
    print(f"check 2 bit-exact model == integer convolution ({len(x)} samples) : {'PASS' if ok2 else 'FAIL'}")

    acc_worst = int(np.abs(q).sum()) * FULL
    y_worst = (acc_worst + (1 << (a.f - 1))) >> a.f
    ok3 = acc_worst < 2 ** (a.acc - 1) and y_worst < 2 ** (a.wout - 1) and max(abs(v) for v in y) < 2 ** (a.wout - 1)
    print(f"check 3 worst case |acc| {acc_worst} < 2^{a.acc - 1}, |y| {y_worst} < 2^{a.wout - 1} : "
          f"{'PASS' if ok3 else 'FAIL'}")

    imp = y[: a.ntap]
    ok4a = np.array_equal(np.array(imp), (100000 * q + (1 << (a.f - 1))) >> a.f)
    step_end = y[len(seg[0][1]) + len(seg[1][1]) - 1]
    ok4b = step_end == FULL
    print(f"check 4 impulse read-back == q, DC step +{FULL} -> {step_end} : "
          f"{'PASS' if (ok4a and ok4b) else 'FAIL'}")

    # padded with x words up to the testbench memory size (NMAX = 4096): the testbench
    # uses the first x word as the end marker, and $readmemh gets a full file
    nmax = 4096
    pad = nmax - len(x)
    with open(data / "fir_in.mem", "w") as fo:
        fo.write("\n".join([f"{v & ((1 << 20) - 1):05x}" for v in x] + ["xxxxx"] * pad) + "\n")
    with open(data / "fir_golden.mem", "w") as fo:
        fo.write("\n".join([f"{v & ((1 << a.wout) - 1):06x}" for v in y] + ["xxxxxx"] * pad) + "\n")
    with open(data / "fir_golden.txt", "w") as fo:
        fo.write("\n".join(str(v) for v in y) + "\n")
    with open(data / "fir_segments.txt", "w") as fo:
        i0 = 0
        for name, s in seg:
            fo.write(f"{name} {i0} {i0 + len(s) - 1}\n")
            i0 += len(s)
    print(f"stimulus: {len(x)} samples, segments: " + ", ".join(f"{n}({len(s)})" for n, s in seg))

    # illustrative: amplitude of the f6 tone after CIC and after CIC+FIR (few points, NOT an SNDR)
    i0 = len(x) - len(cic_out)
    kk = np.arange(len(cic_out))
    w0 = 2 * np.pi * (13.0 / 4096.0 * R) * kk
    for name, sig, skip in [("CIC only", np.array(cic_out, float), NCIC + 1),
                            ("CIC+FIR", np.array(y[i0:], float), NCIC + 1 + a.ntap)]:
        s = sig[skip:] / FULL
        M = np.column_stack([np.sin(w0[skip:]), np.cos(w0[skip:]), np.ones(s.size)])
        c, *_ = np.linalg.lstsq(M, s, rcond=None)
        print(f"        f6 tone {name:8s}: amplitude {np.hypot(c[0], c[1]):.4f} FS ({s.size} points, illustrative)")
    print("        expected: 0.5 FS x gain at the tone (CIC only %.4f, CIC+FIR %.4f)"
          % (0.5 * h_cic([f_tone])[0], 0.5 * g_tone))
    print(f"files written to {data} and {blk / 'rtl/fir_coefs.vh'}")
    return 0 if (ok1 and ok2 and ok3 and ok4a and ok4b) else 1


if __name__ == "__main__":
    sys.exit(main())
